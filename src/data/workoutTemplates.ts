/**
 * Clona una plantilla maestra para crear una rutina de usuario totalmente independiente
 */
export const instantiateRoutineFromTemplate = (
  templateId: string,
  userId: string,
  customName?: string
): WorkoutRoutine => {
  const template = MASTER_WORKOUT_TEMPLATES.find(t => t.id === templateId) || MASTER_WORKOUT_TEMPLATES[0];
  const now = new Date().toISOString();
  const routineId = `routine_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;

  const clonedDays = template.days.map((day, dIdx) => ({
    ...day,
    exercises: day.exercises.map((cfg, cIdx) => ({
      ...cfg,
      id: `cfg_${routineId}_d${dIdx + 1}_ex${cIdx + 1}`,
    })),
  }));

  return {
    id: routineId,
    userId,
    name: customName || template.name,
    description: template.description,
    goal: template.goal,
    frequencyDays: template.frequencyDays,
    days: clonedDays,
    isDefault: true,
    sourceTemplateId: template.id,
    createdAt: now,
    updatedAt: now,
  };
};

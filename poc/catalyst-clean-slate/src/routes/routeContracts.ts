  readonly authPolicy: RouteAuthPolicy;
  readonly csrfPolicy: RouteCsrfPolicy;
  readonly requiresCsrf: boolean;
  readonly requiresCatalystLiveCheck: boolean;
  readonly allowedRoles: readonly ContractUserRole[];

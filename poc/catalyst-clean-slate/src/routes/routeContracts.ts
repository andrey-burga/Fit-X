export type ContractAuthLevel =
  | 'session_bootstrap'
  | 'session_registered'
  | 'admin'
  | 'superadmin_verified_only';

export type RouteAuthPolicy =
  | 'catalyst_exchange'
  | 'hmac_session'
  | 'catalyst_or_hmac_inspect';

export type RouteCsrfPolicy =
  | 'pre_session_catalyst_exchange'
  | 'signed_session_bound'
  | 'none_safe_get';

export type ContractUserRole = 'athlete' | 'admin' | 'superadmin';

